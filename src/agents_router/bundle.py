"""App runtime ownership and paths, without looking at or changing the user's setup.

The app installer writes ``<runtime>/agt-bundle.json`` before publishing a runtime
at ``$AGT_APP_SUPPORT/runtimes/<version>``. Schema 1 is a JSON object with
``schema_version: 1``, ``source: "app"``, ``app_version``, ``runtime_version``,
``python_version`` (nonempty strings), and ``plugin_path: "plugin"`` (a relative
directory inside that runtime). The interpreter is ``bin/python3``. Both the
running package and interpreter must belong to this manifest's physical runtime;
an app on disk, an environment variable or a path name alone never claims a CLI.

AGT_APP_SUPPORT overrides ~/Library/Application Support/Agents Router.
AGT_BIN_DIR overrides ~/.local/bin (the public symlink, not support/bin/agt).
Stable entry points use support/bin/agt; job helpers retain the physical runtime.
"""

from __future__ import annotations

from dataclasses import dataclass
import json
import os
from pathlib import Path
import re
import shlex
import shutil
import sys
import sysconfig
import tempfile

from agents_router import __version__

MANIFEST = "agt-bundle.json"


def app_support() -> Path:
    return Path(os.environ.get("AGT_APP_SUPPORT") or Path.home() / "Library/Application Support/Agents Router").expanduser().absolute()


def bin_dir() -> Path:
    return Path(os.environ.get("AGT_BIN_DIR") or Path.home() / ".local/bin").expanduser().absolute()


def stable_launcher() -> Path:
    # Do not resolve current or the public symlink here.
    return app_support() / "bin/agt"


@dataclass(frozen=True)
class AppInstall:
    runtime: Path
    app_version: str
    runtime_version: str
    python_version: str
    plugin: Path

    @property
    def python(self) -> Path:
        return (self.runtime / "bin/python3").resolve()


def detect(*, executable: str | Path | None = None, package_file: str | Path | None = None) -> AppInstall | None:
    """Detect the running copy, including when Python was reached through current.

    Explicit arguments let checks inspect a staged runtime without changing the
    process's interpreter. Nothing is inferred from AGT_APP_SUPPORT alone.
    """
    try:
        python = Path(executable or sys.executable).resolve()
        package = Path(package_file or __file__).resolve()
        for root in package.parents:
            if not python.is_relative_to(root):
                continue
            manifest = root / MANIFEST
            if not manifest.is_file():
                continue
            data = json.loads(manifest.read_text(encoding="utf-8"))
            if (not isinstance(data, dict) or type(data.get("schema_version")) is not int
                    or data["schema_version"] != 1 or data.get("source") != "app"):
                return None
            if any(not isinstance(data.get(key), str) or not data[key].strip()
                   for key in ("app_version", "runtime_version", "python_version", "plugin_path")):
                return None
            if any(not re.fullmatch(r"[0-9][A-Za-z0-9.+-]*", data[key]) for key in ("app_version", "runtime_version", "python_version")):
                return None
            relative = Path(data["plugin_path"])
            plugin = (root / relative).resolve()
            if relative.is_absolute() or not plugin.is_relative_to(root) or plugin == root:
                return None
            if python != (root / "bin/python3").resolve():
                return None
            return AppInstall(root, data["app_version"], data["runtime_version"], data["python_version"], plugin)
    except (OSError, ValueError, RuntimeError):
        pass
    return None


def installation() -> dict[str, str]:
    """Compact usage contract; pip/editable/checkouts belong to the external source."""
    if detect():
        source = "app"
    else:
        from agents_router.setup import _install_info

        method, _ = _install_info()
        source = "pipx" if method.startswith("pipx") else "uv" if method == "uv" else "source"
    return {"source": source, "version": __version__}


def plugin_source(install: AppInstall) -> Path:
    """An install-specific copy of the shipped tree, with stable MCP and hook commands.

    Runtime payloads stay immutable. The copy lives beside runtimes and is
    regenerated by setup/update, never downloaded. Version and launcher path
    identify the copy so another isolated install cannot reuse its commands.
    """
    return app_support() / "plugins" / install.runtime_version


def validate_plugin(install: AppInstall) -> None:
    """Check the required offline payload before running any host command."""
    # A missing or damaged payload fails locally rather than falling back to GitHub.
    for name in (".claude-plugin/plugin.json", ".claude-plugin/marketplace.json", "hooks/hooks.json"):
        if not (install.plugin / name).is_file():
            raise ValueError(f"bundled plugin is missing {install.plugin / name}; repair Agents Router in the app")
    metadata = json.loads((install.plugin / ".claude-plugin/plugin.json").read_text(encoding="utf-8"))
    if not isinstance(metadata, dict) or metadata.get("version") != install.runtime_version:
        raise ValueError("bundled plugin version differs from the runtime; repair Agents Router in the app")


def prepare_plugin(install: AppInstall) -> Path:
    """Copy the shipped plugin locally and pin commands without editing the runtime."""
    from agents_router.fsutil import write_json

    validate_plugin(install)
    target = plugin_source(install)
    target.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix=".plugin-", dir=target.parent) as temporary:
        staged = Path(temporary) / "plugin"
        shutil.copytree(install.plugin, staged)
        launcher = str(stable_launcher())

        def pin(value):
            if isinstance(value, dict):
                return {key: (launcher if item == "agt" else shlex.quote(launcher) + item[3:])
                        if key == "command" and isinstance(item, str) and (item == "agt" or item.startswith("agt "))
                        else pin(item) for key, item in value.items()}
            return [pin(item) for item in value] if isinstance(value, list) else value

        for name in (".claude-plugin/plugin.json", "mcp_config.json", "hooks/hooks.json"):
            path = staged / name
            if path.is_file():
                write_json(path, pin(json.loads(path.read_text(encoding="utf-8"))))
        # Keep the marketplace directory itself in place: hosts may already hold it.
        shutil.copytree(staged, target, dirs_exist_ok=True)
    return target


def diagnostics() -> dict:
    """Install versions and executable PATH entries; never start a shell or another agt."""
    import platform

    install = detect()
    paths = []
    for folder in os.get_exec_path():
        candidate = Path(folder or ".").absolute() / ("agt.exe" if os.name == "nt" else "agt")
        if candidate.is_file() and os.access(candidate, os.X_OK) and str(candidate) not in paths:
            paths.append(str(candidate))
    expected = stable_launcher() if install else Path(sysconfig.get_path("scripts")) / ("agt.exe" if os.name == "nt" else "agt")
    conflicts = [path for path in paths if Path(path).resolve() != expected.resolve()]
    return {**installation(), "app_version": install.app_version if install else None,
            "runtime_version": install.runtime_version if install else __version__,
            "python_version": platform.python_version(), "bundled_python_version": install.python_version if install else None,
            "python": str(Path(sys.executable).resolve()), "runtime": str(install.runtime) if install else None,
            "launcher": str(expected), "public_launcher": str(bin_dir() / "agt"),
            "path_entries": paths, "path_conflicts": conflicts}


def doctor_lines(report: dict, *, verbose: bool = False) -> list[str]:
    versions = f"agt {report['version']}, python {report['python_version']}"
    if report["app_version"]:
        versions = f"app {report['app_version']}, " + versions
    lines = [f"install: {report['source']} ({versions})"]
    lines += [f"warn: another agt on PATH: {path}" for path in report["path_conflicts"]]
    if verbose:
        lines += [f"  {key}: {report[key]}" for key in ("runtime_version", "bundled_python_version", "python", "runtime", "launcher", "public_launcher")
                  if report[key] is not None]
        lines += [f"  PATH agt: {path}" for path in report["path_entries"]]
    return lines
